 ### Question 49 Find departments where the average treatment cost is higher than the overall average 
 # treatment cost of the hospital.
SELECT 
    d.department_name, 
    AVG(a.treatment_cost) AS avg_department_cost
FROM departments d
INNER JOIN doctors doc ON d.department_id = doc.department_id
INNER JOIN appointments a ON doc.doctor_id = a.doctor_id
GROUP BY d.department_id, d.department_name
HAVING AVG(a.treatment_cost) > (
    SELECT AVG(treatment_cost) 
    FROM appointments
);

#Question 50The hospital management wants to reward loyal patients. Display the patients who have visited the hospital 
#at least three times and whose total treatment cost exceeds ₹10,000.

SELECT 
    p.patient_id,
    p.patient_name,
    COUNT(a.appointment_id) AS total_visits,
    SUM(a.treatment_cost) AS total_spent
FROM 
    patients p
INNER JOIN 
    appointments a ON p.patient_id = a.patient_id
GROUP BY 
    p.patient_id, 
    p.patient_name
HAVING 
    COUNT(a.appointment_id) >= 2 
    AND SUM(a.treatment_cost) > 10000
ORDER BY 
    total_spent DESC;